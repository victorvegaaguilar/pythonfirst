# Operadores de comparación

print(3 > 4)  # Mayor que
print(3 < 4)  # Menor que
print(3 >= 4)  # Mayor o igual que
print(3 <= 4)  # Menor o igual que
print(3 == 4)  # Igual que
print(3 != 4)  # Distinto que
print(3 is 4)  # Identidad
print(3 is not 4)  # No identidad
print(3 in [1, 2, 3])  # Pertenencia
print(3 not in [1, 2, 3])  # No pertenencia
print(3 > 4 and 3 < 4)  # Operador lógico AND
print(3 > 4 or 3 < 4)  # Operador lógico OR


print("Hola" == "Hola")  # Comparación de strings
print("Hola" == "Zola")  # Comparación de strings
print(len("Hola") == len("Zola"))  # Comparación de strings
print("aaaa" > "AAAA")  # Comparación de strings

